const kebab = (name: string) => name.replace(/[A-Z]/g, (ch) => `-${ch.toLowerCase()}`);

/** `{ bgElevated: '#fff' }` -> `{ '--mp-bg-elevated': '#fff' }` */
export function cssVariables(theme: ThemeName): Record<string, string> {
  const vars: Record<string, string> = {};
  const colors = themes[theme];
  // Object.entries() on an interface loses the value type; iterate typed keys instead.
  for (const name of Object.keys(colors) as (keyof SemanticColors)[]) {
    vars[`--mp-${kebab(name)}`] = colors[name];
  }
  vars['--mp-shadow-card'] = shadows[theme].card;
  vars['--mp-shadow-pop'] = shadows[theme].pop;
  return vars;
}

function staticVariables(): Record<string, string> {
  const vars: Record<string, string> = {};
  for (const [name, value] of Object.entries(brand)) vars[`--mp-brand-${kebab(name)}`] = value;
  for (const [name, value] of Object.entries(radii)) vars[`--mp-radius-${name}`] = value;
  vars['--mp-duration-fast'] = motion.fast;
  vars['--mp-duration-base'] = motion.base;
  vars['--mp-duration-slow'] = motion.slow;
  vars['--mp-ease'] = motion.ease;
  return vars;
}

const block = (vars: Record<string, string>, indent: string) =>
  Object.entries(vars)
    .map(([name, value]) => `${indent}${name}: ${value};`)
    .join('\n');

/**
 * Light by default; dark via `data-theme="dark"` on <html>, or via the OS setting
 * when no explicit theme was chosen (works before JavaScript runs).
 */
export function tokensCss(): string {
  const dark = cssVariables('dark');
  return [
    '/* Generated by @mp/design-tokens. Do not edit. */',
    ':root {',
    '  color-scheme: light;',
    block({ ...staticVariables(), ...cssVariables('light') }, '  '),
    '}',
    ":root[data-theme='dark'] {",
    '  color-scheme: dark;',
    block(dark, '  '),
    '}',
    '@media (prefers-color-scheme: dark) {',
    "  :root:not([data-theme='light']) {",
    '    color-scheme: dark;',
    block(dark, '    '),
    '  }',
    '}',
    '',
  ].join('\n');
}

function luminance(hex: string): number {
  const match = /^#([0-9a-f]{6})/i.exec(hex);
  if (!match?.[1]) throw new Error(`Not a hex color: ${hex}`);
  const value = match[1];
  const channel = (offset: number) => {
    const c = parseInt(value.slice(offset, offset + 2), 16) / 255;
    return c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  };
  return 0.2126 * channel(0) + 0.7152 * channel(2) + 0.0722 * channel(4);
}

/** WCAG 2.x contrast ratio between two opaque hex colors (1..21). */
export function contrastRatio(foreground: string, background: string): number {
  const [hi, lo] = [luminance(foreground), luminance(background)].sort((a, b) => b - a);
  return ((hi ?? 0) + 0.05) / ((lo ?? 0) + 0.05);
}
